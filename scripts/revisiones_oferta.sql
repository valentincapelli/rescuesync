-- Versiones de ofertas: ejecutar una vez en la base PostgreSQL de RescueSync si no se usa ddl-auto=update.
-- Aditivo e idempotente: no modifica las ofertas existentes. Las ofertas viejas quedan con una sola versión (el alta).
BEGIN;

CREATE TABLE IF NOT EXISTS public.revisiones_oferta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    oferta_id BIGINT NOT NULL,
    autor_id BIGINT NOT NULL,
    cantidad_anterior INTEGER NOT NULL,
    cantidad_nueva INTEGER NOT NULL,
    observaciones_anteriores TEXT,
    observaciones_nuevas TEXT,
    CONSTRAINT fk_revision_oferta_oferta FOREIGN KEY (oferta_id) REFERENCES public.ofertas(id),
    CONSTRAINT fk_revision_oferta_autor FOREIGN KEY (autor_id) REFERENCES public.usuarios(id)
);

CREATE INDEX IF NOT EXISTS idx_revision_oferta_oferta ON public.revisiones_oferta (oferta_id);

COMMIT;
