CREATE TABLE IF NOT EXISTS public.intenciones_seleccion_bonita (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    oferta_id BIGINT NOT NULL,
    estado VARCHAR(20) NOT NULL,
    bonita_case_id BIGINT,
    bonita_task_id VARCHAR(100),
    continuar_seleccionando_input BOOLEAN,
    ultimo_intento_en TIMESTAMP WITH TIME ZONE,
    detalle_incidente VARCHAR(500),
    intentos INTEGER NOT NULL DEFAULT 0,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_intencion_seleccion_oferta FOREIGN KEY (oferta_id) REFERENCES public.ofertas(id),
    CONSTRAINT uk_intencion_seleccion_oferta UNIQUE (oferta_id),
    CONSTRAINT uk_intencion_seleccion_task UNIQUE (bonita_task_id),
    CONSTRAINT ck_intencion_seleccion_estado CHECK (estado IN
        ('PENDIENTE', 'DESPACHANDO', 'EN_CICLO', 'LIBERADA', 'INCIDENTE'))
);

-- Si la tabla fue creada por ddl-auto o por una versión anterior de este script.
ALTER TABLE public.intenciones_seleccion_bonita
    ADD COLUMN IF NOT EXISTS ultimo_intento_en TIMESTAMP WITH TIME ZONE;
ALTER TABLE public.intenciones_seleccion_bonita
    ADD COLUMN IF NOT EXISTS detalle_incidente VARCHAR(500);
ALTER TABLE public.intenciones_seleccion_bonita
    ADD COLUMN IF NOT EXISTS intentos INTEGER NOT NULL DEFAULT 0;

COMMIT;
